export type MsgKey = keyof (typeof dict)["en"];

export function t(lang: LangCode, key: MsgKey): string {
  return dict[lang][key] ?? dict.en[key];
}

export function detectLang(): LangCode {
  if (typeof navigator === "undefined") return "ru";
  const raw = (navigator.languages?.[0] ?? navigator.language ?? "ru").toLowerCase();
  const short = raw.slice(0, 2) as LangCode;
  if (LANG_CODES.includes(short)) return short;
  return "ru";
}

export function catName(lang: LangCode, id: string, customName?: string): string {
  if (customName) return customName;
  const key = `cat_${id}` as MsgKey;
  if (key in dict.en) return t(lang, key);
  return id;
}

export function catHint(lang: LangCode, id: string): string {
  const key = `hint_${id}` as MsgKey;
  if (key in dict.en) return t(lang, key);
  return "";
}
